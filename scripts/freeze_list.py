"""E9 / D51 (D60): every tunable the oracles, probes, gate and harness use, with its current value, so all of
them can be frozen before any held-out run. Writes docs/d51_freeze.md (generated; the freeze itself is a
decision in logs/decisions.md). Usage: python scripts/freeze_list.py"""

import dataclasses
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from webtester import (annotate, consistency, crossview, envcheck, evaluate, gate, norms, openapi, policies,  # noqa: E402
                       probes5, reach, runner)
from webtester.config import RunConfig  # noqa: E402
from webtester.gate import GateConfig  # noqa: E402


def module_consts(mod) -> list[tuple[str, object]]:
    out = []
    for k, v in vars(mod).items():
        if re.fullmatch(r"(MAX|MIN|CAP|BETA|K_)[A-Z0-9_]*|[A-Z][A-Z0-9_]*_S|CAPS|AXES|SEVERITY_WEIGHT|PRIMARY|DEFAULT_TIER|NUMERIC_RULES|TIME_RULES|SEQUENCE_EVERY|ENGINES",
                        k):
            out.append((k, v))
    return out


def main() -> None:
    rows = ["# D51 freeze list (generated by scripts/freeze_list.py; do not edit)", "",
            "Every value below is frozen at the v5.1 lock (E9). A change after the lock is a new version.", "",
            "| Where | Name | Value |", "|---|---|---|"]
    for mod in (consistency, crossview, norms, probes5, envcheck, evaluate, gate, runner, openapi, annotate, reach, policies):
        for k, v in module_consts(mod):
            rows.append(f"| `{mod.__name__.split('.')[-1]}` | {k} | `{v}` |")
    for f in dataclasses.fields(RunConfig):
        if f.name in ("app", "llm", "budget"):
            continue
        d = f.default if f.default is not dataclasses.MISSING else "(factory)"
        rows.append(f"| `RunConfig` | {f.name} | `{d}` |")
    for f in dataclasses.fields(GateConfig):
        rows.append(f"| `GateConfig` | {f.name} | `{f.default}` |")
    tiers = sorted(consistency.TIER.items())
    rows += ["", "Tiers (rule: tier), every rule:", "", ", ".join(f"{r} {t}" for r, t in tiers)]
    (ROOT / "docs/d51_freeze.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote docs/d51_freeze.md ({len(rows)} lines, {len(tiers)} rules)")


if __name__ == "__main__":
    main()
