"""Run registry: one tracked record of every experiment run.

`runs/` holds full traces and is gitignored (traces get large). The registry
copies each run's small summary and findings into logs/experiments/runs/ and
renders logs/experiments/run_registry.md, merging the hand-written status and
notes from logs/experiments/run_notes.toml (valid / invalid / smoke + why).
"""

from __future__ import annotations

import json
import shutil
import tomllib
from pathlib import Path

from .config import REPO_ROOT

LOG_DIR = REPO_ROOT / "logs" / "experiments"
NOTES = LOG_DIR / "run_notes.toml"


def _faults_found(s: dict) -> str:
    fd = s.get("fault_detection")
    if not fd:
        return "–"
    hit = sorted(f for f, d in fd.items() if d["detected"])
    return f"{len(hit)}/{len(fd)}" + (f" ({', '.join(hit)})" if hit else "")


def condition(agent: str | None, workers: int | None) -> str:
    """Research-plan name of a run's condition (agent b1 with N > 1 workers is B2)."""
    if agent == "b1" and (workers or 1) > 1:
        return "B2"
    return {"b0": "B0", "b1": "B1", "b3": "B3", "b3local": "B3-local", "b3v2": "B3v2", "b3v2local": "B3v2-local",
            "b4": "B4", "b4nog1": "A-G1", "b4nog3": "A-G3"}.get(agent or "", agent or "?")


def _findings(s: dict) -> str:
    """Candidates, plus gate-confirmed ones for gated runs (G2)."""
    if "findings_confirmed" in s:
        return f"{s.get('findings')} ({s['findings_confirmed']} conf.)"
    return str(s.get("findings"))


def _health(s: dict) -> str:
    h = s.get("health") or {}
    if h.get("ok"):
        return "ok"
    bits = []
    if h.get("llm_failures"):
        bits.append(f"{h['llm_failures']} LLM failures")
    if h.get("stalled"):
        bits.append(f"stall {h['max_step_gap_s']:.0f}s")
    if h.get("gate_ok") is False:
        bits.append("gate failed")
    if not s.get("steps"):
        bits.append("no steps")
    return "⚠ " + (", ".join(bits) or "early stop")


def _reach(run_dir: Path, faults: list[str]) -> dict | None:
    from .metrics import load_fault_catalog, reach_from_trace

    cfg_path = run_dir / "config.json"
    if not cfg_path.exists():
        return None
    compose_dir = json.loads(cfg_path.read_text(encoding="utf-8")).get("app", {}).get("compose_dir") or ""
    catalog_path = REPO_ROOT / compose_dir / "faults" / "faults.toml"
    if not catalog_path.exists():
        return None
    return reach_from_trace(run_dir / "trace.jsonl", faults, load_fault_catalog(catalog_path))


def build(runs_dir: Path | None = None) -> Path:
    runs_dir = runs_dir or REPO_ROOT / "runs"
    notes = tomllib.loads(NOTES.read_text(encoding="utf-8")) if NOTES.exists() else {}
    archive = LOG_DIR / "runs"
    archive.mkdir(parents=True, exist_ok=True)

    rows = []
    for d in sorted(p for p in runs_dir.iterdir() if p.is_dir() and not p.name.startswith("_")):
        if not (d / "summary.json").exists():
            continue
        s = json.loads((d / "summary.json").read_text(encoding="utf-8"))
        if "stalled" not in (s.get("health") or {}) and (d / "trace.jsonl").exists():
            # Older runs: recompute the summary so the health check is present.
            from .metrics import summarize

            fd = s.get("fault_detection")
            s = summarize(d / "trace.jsonl") | ({"fault_detection": fd} if fd else {})
            (d / "summary.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
        if "fault_reach" not in s and s.get("faults") and (d / "trace.jsonl").exists():
            # Runs from before the `reach` rules: add the offline trigger analysis (metrics.fault_reach).
            reach = _reach(d, s["faults"])
            if reach is not None:
                s["fault_reach"] = reach
                (d / "summary.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
        dest = archive / d.name
        dest.mkdir(exist_ok=True)
        for name in ("summary.json", "findings.json", "config.json"):
            if (d / name).exists():
                shutil.copy2(d / name, dest / name)
        n = notes.get(d.name, {})
        rows.append((d.name, s, n.get("status", "unreviewed"), n.get("note", "")))

    lines = [
        "# Run registry",
        "",
        "Generated by `python -m webtester registry`; do not edit by hand. Status and notes come from "
        "[run_notes.toml](run_notes.toml). Full traces stay in `runs/` (gitignored); summaries, findings and "
        "configs are archived in [runs/](runs/).",
        "",
        "Only runs marked **valid** count towards reported results.",
        "",
        "| Run | Status | Health | Condition | N | Faults on | Min | Steps | States | Routes | Dup. actions | Findings | Faults found | Tokens | Note |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for rid, s, status, note in rows:
        faults = s.get("faults") or []
        lines.append(
            f"| `{rid}` | {status} | {_health(s)} | {condition(s.get('agent'), s.get('workers'))} | {s.get('workers')} | {len(faults)} | {s.get('wall_minutes')} "
            f"| {s.get('steps')} | {s.get('unique_states')} | {s.get('unique_routes')} "
            f"| {s.get('duplicate_action_rate', 0):.0%} | {_findings(s)} | {_faults_found(s)} "
            f"| {s.get('tokens_total')} | {note} |"
        )
    out = LOG_DIR / "run_registry.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
